for (const [language, exportName, native] of locales) {
  const shared = (await import(new URL(`../src/i18n/${language}.ts`, import.meta.url)))[exportName];
  const labels = {
    common: { ...shared.common, ...native.common },
    status: shared.status,
    shortcuts: shared.shortcuts,
    loop: shared.loop,
    hardware: shared.hardware,
    contextMenu: {
      ...shared.contextMenu,
      openNetworkStream: shared.streamDialog.title,
      mediaProperties: native.mediaProperties.title,
    },
    settings: {
      title: shared.settings.title,
      nav: {
        appearance: shared.settings.nav.appearance,
        playback: shared.settings.nav.playback,
        shortcuts: shared.settings.nav.shortcuts,
        about: shared.settings.nav.about,
      },
      appearance: {
        ...shared.settings.appearance,
        ...native.appearance,
      },
      playback: shared.settings.playback,
      shellPreview: { ...shared.settings.shellPreview, ...native.shellPreview },
      shortcuts: shared.settings.shortcuts,
      about: {
        ...shared.settings.about,
        ...native.updates,
        description: native.about,
        updateAvailable: shared.settings.about.updateAvailable("{version}"),
        updateCheckFailed: shared.settings.about.updateCheckFailed("{message}"),
      },
    },
    media: {
      ...shared.media,
      dropToPlay: native.dropToPlay,
      doubleClickOpen: native.doubleClickOpen,
      openingFilePicker: native.openingFilePicker,
      quickOpen: native.quickOpen,
      properties: native.mediaProperties,
    },
    controls: shared.controls,
    streamDialog: shared.streamDialog,
    dialog: {
      mediaFiles: shared.dialog.mediaFiles,
      mediaFolder: shared.dialog.mediaFolder,
      subtitle: shared.dialog.subtitle,
    },
  };
  delete labels.contextMenu.externalCapture;
  delete labels.settings.appearance.pluginTheme;

  const file = new URL(`${language}.json`, nativeLocales);
  const generated = `${JSON.stringify(labels, null, 2)}\n`;
  if (check) {
    const existing = (await readFile(file, "utf8")).replace(/\r\n/g, "\n");
    if (existing !== generated) throw new Error(`Native ${language} labels are stale. Run node scripts/sync-native-locales.mjs.`);
  } else {
    await writeFile(file, generated);
  }
}
